def _coerce_manifest_dict(manifest: Any) -> dict[str, Any]:
	if manifest is None:
		return default_offline_eval_manifest()
	if isinstance(manifest, dict):
		return manifest
	to_dict = getattr(manifest, "to_dict", None)
	if callable(to_dict):
		res = to_dict()
		if isinstance(res, dict):
			return res
	raise TypeError(f"Expected manifest dict or SimManifest object, got {type(manifest).__name__}")


def load_manifest(path: str | Path) -> dict[str, Any]:
	"""Load and validate a SimManifest JSON file from disk."""
	raw = Path(path).read_text(encoding="utf-8-sig")
	parsed = json.loads(raw)
	if not isinstance(parsed, dict):
		raise ValueError(f"Manifest JSON in '{path}' must be an object, got {type(parsed).__name__}")
	return parsed


def resolve_manifest_path(manifest: Any, handle_path: str) -> Any:
	"""Resolve a top-level field or dotted path (e.g. 'bays.main_lift', 'metadata.target_date')."""
	if not handle_path or not isinstance(handle_path, str):
		raise KeyError("SimManifest handle_path must be a non-empty string")
	data = _coerce_manifest_dict(manifest)
	parts = handle_path.split(".")
	cur: Any = data
	for idx, part in enumerate(parts):
		if isinstance(cur, dict):
			if part not in cur:
				prefix = ".".join(parts[:idx]) or "SimManifest"
				raise KeyError(f"Unknown handle '{part}' in {prefix} ('{handle_path}')")
			cur = cur[part]
		else:
			prefix = ".".join(parts[:idx]) or "SimManifest"
			raise KeyError(f"Cannot traverse non-mapping {prefix} for '{handle_path}'")
	return cur


def interpolate_manifest(template: str, manifest: Any) -> str:
	"""Replace '{{category.handle}}' and '{manifest:category.handle}' placeholders from manifest."""
	if not isinstance(template, str):
		raise TypeError("template must be a str")
	data = _coerce_manifest_dict(manifest)

	def _replace(match: re.Match[str]) -> str:
		return str(resolve_manifest_path(data, match.group(1)))

	rendered = _DOUBLE_BRACE_PATTERN.sub(_replace, template)
	return _PREFIX_BRACE_PATTERN.sub(_replace, rendered)


def interpolate_value(value: Any, manifest: Any) -> Any:
	"""Recursively interpolate manifest placeholders across strings, lists, tuples, and dicts."""
	if isinstance(value, str):
		return interpolate_manifest(value, manifest)
	if isinstance(value, list):
		return [interpolate_value(item, manifest) for item in value]
	if isinstance(value, tuple):
		return tuple(interpolate_value(item, manifest) for item in value)
	if isinstance(value, dict):
		return {k: interpolate_value(v, manifest) for k, v in value.items()}
	return value


def extract_json_from_stdout(stdout: str, *, required_keys: tuple[str, ...] = ()) -> dict[str, Any]:
	"""Extract a JSON dict from bench execute / test-in-slot.ps1 stdout with log prefixes."""
	text = (stdout or "").strip()
	if not text:
		raise ValueError("Empty stdout; expected JSON output")

	try:
		direct = json.loads(text)
		if isinstance(direct, dict) and all(k in direct for k in required_keys):
			return direct
	except json.JSONDecodeError:
		pass

	decoder = json.JSONDecoder()
	candidates: list[tuple[int, dict[str, Any]]] = []
	for match in re.finditer(r"(?m)^\{", text):
		try:
			obj, end_idx = decoder.raw_decode(text, match.start())
		except json.JSONDecodeError:
			continue
		if isinstance(obj, dict) and all(k in obj for k in required_keys):
			candidates.append((end_idx, obj))

	if candidates:
		# Prefer the object closest to the end of stdout (actual bench execute output)
		candidates.sort(key=lambda item: item[0], reverse=True)
		return candidates[0][1]

	# Fallback: scan all '{' positions from last to first
	for idx in range(len(text) - 1, -1, -1):
		if text[idx] != "{":
			continue
		try:
			obj, _ = decoder.raw_decode(text, idx)
		except json.JSONDecodeError:
			continue
		if isinstance(obj, dict) and all(k in obj for k in required_keys):
			return obj

	raise ValueError(f"Could not locate valid JSON object in stdout: {text[:240]}")


def _ps_quote(value: str) -> str:
	return "'" + value.replace("'", "''") + "'"


def _build_slot_ps_command(
	slot: int,
	*,
	execute_fn: Optional[str] = None,
	serve_action: Optional[str] = None,
	clean_reinstall: bool = False,
	keep_db: bool = True,
	extra_args: Optional[list[str]] = None,
	script_path: Path = _TEST_IN_SLOT_PS1,
) -> list[str]:
	if not 1 <= int(slot) <= 8:
		raise ValueError(f"Slot must be between 1 and 8, got {slot}")
	if serve_action and not 1 <= int(slot) <= 5:
		raise ValueError(f"Serve mode only supports slots 1..5, got {slot}")

	if extra_args:
		parts = [f"& {_ps_quote(str(script_path))}", "-Slot", str(int(slot))]
		if clean_reinstall:
			parts.append("-CleanReinstall")
		elif keep_db and serve_action != "stop":
			parts.append("-KeepDb")
		if execute_fn:
			parts.extend(["-Execute", _ps_quote(execute_fn)])
		if serve_action:
			parts.extend(["-Serve", _ps_quote(serve_action)])
		parts.extend(["-ExtraArgs", ",".join(_ps_quote(a) for a in extra_args)])
		return ["powershell", "-ExecutionPolicy", "Bypass", "-Command", " ".join(parts)]

	cmd = [
		"powershell",
		"-ExecutionPolicy",
		"Bypass",
		"-File",
		str(script_path),
		"-Slot",
		str(int(slot)),
	]
	if clean_reinstall:
		cmd.append("-CleanReinstall")
	elif keep_db and serve_action != "stop":
		cmd.append("-KeepDb")
	if execute_fn:
		cmd.extend(["-Execute", execute_fn])
	if serve_action:
		cmd.extend(["-Serve", serve_action])
	return cmd


def _default_subprocess_runner(cmd: list[str], timeout: int = 600) -> subprocess.CompletedProcess[str]:
	return subprocess.run(
		cmd,
		cwd=str(_MONOREPO_ROOT),
		capture_output=True,
		text=True,
		timeout=timeout,
	)


def seed_profile_in_slot(
	slot: int,
	execute_fn: str = "ism.testing.profiles.seed_eval_standard",
	*,
	extra_args: Optional[list[str]] = None,
	clean_reinstall: bool = False,
	keep_db: bool = True,
	runner: Optional[Callable[[list[str]], Any]] = None,
) -> dict[str, Any]:
	"""Execute a SimManifest seeder function in a dedicated bench slot and parse JSON stdout."""
	cmd = _build_slot_ps_command(
		slot,
		execute_fn=execute_fn,
		clean_reinstall=clean_reinstall,
		keep_db=keep_db,
		extra_args=extra_args,
	)
	run_fn = runner or _default_subprocess_runner
	proc = run_fn(cmd)
	if proc.returncode != 0:
		err = (proc.stderr or proc.stdout or "").strip()
		raise RuntimeError(f"Slot {slot} execute '{execute_fn}' failed (rc={proc.returncode}): {err[:400]}")
	return extract_json_from_stdout(proc.stdout, required_keys=("profile", "company"))



def parse_seed_specs(
	seeds: Optional[list[str]] = None,
	seed_range: Optional[str] = None,
	default_seeds: tuple[int, ...] = tuple(range(1, 11)),
) -> list[int]:
	"""Parse --seeds and --seed-range arguments into a deduplicated list of integer seeds."""
	parsed: list[int] = []
	for token in seeds or []:
		for part in str(token).split(","):
			cleaned = part.strip()
			if not cleaned:
				continue
			parsed.append(int(cleaned))

	if seed_range:
		raw = seed_range.strip()
		match = re.match(r"^(-?\d+)\s*(?:\.\.|:|-)\s*(-?\d+)$", raw)
		if not match:
			raise ValueError(f"Invalid --seed-range '{seed_range}'; expected e.g. '1..5' or '1-5'")
		start = int(match.group(1))
		end = int(match.group(2))
		if start > end:
			raise ValueError(f"Invalid --seed-range '{seed_range}': start > end")
		parsed.extend(range(start, end + 1))

	if not parsed:
		parsed = list(default_seeds)

	seen: set[int] = set()
	ordered: list[int] = []
	for s in parsed:
		if s not in seen:
			seen.add(s)
			ordered.append(s)
	return ordered


@dataclass
class ProbeSpec:
	"""Single CLI edge-case resilience probe derived from a monte_carlo SimManifest."""

	id: str
	category: str
	description: str
	command: str
	args: list[str]
	expect_error: bool = False
	check_fn: Optional[Callable[[dict[str, Any], str, int], list[tuple[str, bool, str]]]] = None


def _run_ism_cli(
	args: list[str],
	env: Optional[dict[str, str]] = None,
) -> tuple[int, str, str, Optional[dict[str, Any]], float]:
	"""Execute `python -m tools.cli --json ...` and return (rc, stdout, stderr, parsed_json, ms)."""
	cmd = [sys.executable, "-m", "tools.cli", "--json", *args]
	run_env = os.environ.copy()
	if env:
		run_env.update(env)
	t0 = time.perf_counter()
	proc = subprocess.run(
		cmd,
		cwd=str(_AGENT_OS_ROOT),
		env=run_env,
		capture_output=True,
		text=True,
		timeout=60,
	)
	elapsed_ms = (time.perf_counter() - t0) * 1000.0
	parsed: Optional[dict[str, Any]] = None
	stdout = (proc.stdout or "").strip()
	if stdout:
		try:
			obj = json.loads(stdout)
			if isinstance(obj, dict):
				parsed = obj
			elif isinstance(obj, list):
				parsed = {"items": obj}
		except json.JSONDecodeError:
			parsed = None
	return proc.returncode, stdout, (proc.stderr or "").strip(), parsed, elapsed_ms



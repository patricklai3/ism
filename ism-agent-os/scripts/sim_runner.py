def build_monte_carlo_probes(
	manifest: dict[str, Any],
	*,
	occupied_slot: Optional[dict[str, Any]] = None,
	leave_tech_ids: Optional[list[str]] = None,
	max_per_category: int = 3,
) -> list[ProbeSpec]:
	"""Generate deterministic CLI resilience probes from a monte_carlo SimManifest."""
	summary = _extract_mc_summary(manifest)
	meta = manifest.get("metadata") or {}
	target_date = str(
		summary.get("target_date")
		or meta.get("target_date")
		or manifest.get("anchor_date")
		or (date.today() + timedelta(days=1)).isoformat()
	)

	probes: list[ProbeSpec] = [_probe_baseline(target_date)]

	conflict_ros = list(summary.get("conflict_ros") or [])
	waiting_ros = list(summary.get("waiting_on_parts_ros") or [])
	unscheduled_ros = list(summary.get("unscheduled_ros") or [])
	over_tol_ros = list(summary.get("over_tolerance_ros") or [])
	partially_approved_ros = list(summary.get("partially_approved_ros") or [])

	# Leave collision probes
	effective_leave_techs = list(leave_tech_ids or summary.get("leave_techs") or summary.get("on_leave_techs") or [])
	if not effective_leave_techs and manifest.get("leave_applications"):
		elena_id = (manifest.get("techs") or {}).get("elena")
		if elena_id:
			effective_leave_techs.append(elena_id)
	for idx, tech_id in enumerate(effective_leave_techs[:max_per_category], start=1):
		probes.append(_probe_leave_collision(target_date, str(tech_id), idx))

	# Conflict probes: estimate on conflict ROs + live occupied-slot collision if discovered or unscheduled available
	for idx, ro_id in enumerate(conflict_ros[:max_per_category], start=1):
		probes.append(_probe_estimate_conflict_ro(str(ro_id), idx))
	if occupied_slot and (unscheduled_ros or conflict_ros):
		probe_ro = str((unscheduled_ros or conflict_ros)[0])
		bay = str(occupied_slot.get("service_bay") or (manifest.get("bays") or {}).get("main_lift") or "Bay 1 - Main Lift")
		time_str = str(occupied_slot.get("scheduled_time") or "09:00")[:5]
		tech_id = occupied_slot.get("assigned_technician")
		probes.append(_probe_conflict_booking(probe_ro, target_date, bay, time_str, tech_id, 1))
	elif conflict_ros and unscheduled_ros:
		main_lift = str((manifest.get("bays") or {}).get("main_lift") or "Bay 1 - Main Lift")
		marcus_id = (manifest.get("techs") or {}).get("marcus")
		probes.append(_probe_conflict_booking(str(unscheduled_ros[0]), target_date, main_lift, "09:00", marcus_id, 1))

	# Stockout / waiting on parts probes
	for idx, ro_id in enumerate(waiting_ros[:max_per_category], start=1):
		probes.append(_probe_stockout(str(ro_id), idx))

	# Unscheduled RO probes
	for idx, ro_id in enumerate(unscheduled_ros[:max_per_category], start=1):
		probes.append(_probe_unscheduled(str(ro_id), target_date, idx))

	# Over-tolerance Shop Action Item probes
	for idx, ro_id in enumerate(over_tol_ros[:max_per_category], start=1):
		probes.append(_probe_over_tolerance(str(ro_id), idx))

	# Lunch break boundary & offline bay guard probes
	bays = manifest.get("bays") or {}
	techs = manifest.get("techs") or {}
	guard_ro = str((unscheduled_ros or conflict_ros or list((manifest.get("ros") or {}).values()))[0]) if (unscheduled_ros or conflict_ros or manifest.get("ros")) else "RO-MC-001"
	alignment_bay = str(bays.get("alignment") or bays.get("main_lift") or "Bay 2 - Alignment & Suspension")
	offline_bay = str(bays.get("offline") or "Bay 5 - Offline")
	devon_id = techs.get("devon")
	probes.append(_probe_lunch_break_boundary(guard_ro, target_date, alignment_bay, devon_id))
	probes.append(_probe_offline_bay_guard(guard_ro, target_date, offline_bay))

	# Stockout alternates, partial-decline deferred sync, write-gate & pricing floor probes
	brake_pkg = str((manifest.get("packages") or {}).get("front_brake_overhaul") or "Front Brake Pads, Rotors & Fluid Overhaul")
	probes.append(_probe_stockout_alternates(brake_pkg))

	for idx, ro_id in enumerate(partially_approved_ros[:max_per_category], start=1):
		probes.append(_probe_partially_approved_deferred(str(ro_id), idx))

	cust_1 = str((manifest.get("customers") or {}).get("retail_1") or "Liam Chen")
	veh_1 = str((manifest.get("vehicles") or {}).get("veh_model3_liam") or DEFAULT_MODEL3_VIN)
	probes.append(_probe_dry_run_write_gate(cust_1, veh_1))
	probes.append(_probe_pricing_floor_contract())

	return probes


